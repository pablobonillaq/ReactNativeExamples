#import "RCTNativeTodos.h"

#import <UIKit/UIKit.h>

// The list is saved as one JSON string under this key of a dedicated
// NSUserDefaults suite (Library/Preferences/native-todos.plist).
static NSString *const kSuiteName = @"native-todos";
static NSString *const kTodosKey = @"todos";
static NSString *const kNextIdKey = @"next_id";

@implementation RCTNativeTodos {
  NSUserDefaults *_defaults;
  NSMutableArray<NSDictionary *> *_todos;
}

- (instancetype)init
{
  if (self = [super init]) {
    _defaults = [[NSUserDefaults alloc] initWithSuiteName:kSuiteName];
  }
  return self;
}

/// Must match TurboModuleRegistry.get('NativeTodos') in the spec, and the
/// modulesProvider entry in package.json.
+ (NSString *)moduleName
{
  return @"NativeTodos";
}

/// Connects this class to the C++ (JSI) object generated by Codegen.
- (std::shared_ptr<facebook::react::TurboModule>)getTurboModule:
    (const facebook::react::ObjCTurboModule::InitParams &)params
{
  return std::make_shared<facebook::react::NativeTodosSpecJSI>(params);
}

#pragma mark - Async methods (Promise in the spec → resolve / reject blocks)

- (void)getAll:(RCTPromiseResolveBlock)resolve reject:(RCTPromiseRejectBlock)reject
{
  @synchronized(self) {
    resolve([[self load] copy]);
  }
}

- (void)search:(NSString *)query
       resolve:(RCTPromiseResolveBlock)resolve
        reject:(RCTPromiseRejectBlock)reject
{
  NSString *needle =
      [query stringByTrimmingCharactersInSet:NSCharacterSet.whitespaceCharacterSet];
  // Ignores case and accents, so "cafe" finds "Café".
  NSStringCompareOptions options = NSCaseInsensitiveSearch | NSDiacriticInsensitiveSearch;
  NSMutableArray *found = [NSMutableArray new];
  @synchronized(self) {
    for (NSDictionary *todo in [self load]) {
      if (needle.length == 0 ||
          [todo[@"text"] rangeOfString:needle options:options].location != NSNotFound) {
        [found addObject:todo];
      }
    }
  }
  NSLog(@"[NativeTodos] search(\"%@\") → %lu result(s)", query, (unsigned long)found.count);
  resolve(found);
}

- (void)add:(NSString *)text
         date:(double)date
    completed:(BOOL)completed
      resolve:(RCTPromiseResolveBlock)resolve
       reject:(RCTPromiseRejectBlock)reject
{
  NSString *trimmed =
      [text stringByTrimmingCharactersInSet:NSCharacterSet.whitespaceCharacterSet];
  if (trimmed.length == 0) {
    reject(@"E_EMPTY_TEXT", @"The todo text can't be empty", nil);
    return;
  }
  NSDictionary *todo;
  @synchronized(self) {
    NSInteger nextId = MAX([_defaults integerForKey:kNextIdKey], 1);
    todo = @{
      @"id" : [NSString stringWithFormat:@"%ld", (long)nextId],
      @"text" : trimmed,
      @"date" : @(date),
      @"completed" : @(completed),
    };
    [[self load] addObject:todo];
    [_defaults setInteger:nextId + 1 forKey:kNextIdKey];
    [self save];
  }
  resolve(todo);
}

- (void)update:(NSString *)todoId
          text:(NSString *_Nullable)text
          date:(NSNumber *_Nullable)date
     completed:(NSNumber *_Nullable)completed
       resolve:(RCTPromiseResolveBlock)resolve
        reject:(RCTPromiseRejectBlock)reject
{
  NSDictionary *updated = nil;
  @synchronized(self) {
    NSMutableArray *list = [self load];
    for (NSUInteger i = 0; i < list.count; i++) {
      if (![list[i][@"id"] isEqualToString:todoId]) {
        continue;
      }
      // nil means "don't change this field".
      NSMutableDictionary *changed = [list[i] mutableCopy];
      if (text != nil) {
        changed[@"text"] = [text
            stringByTrimmingCharactersInSet:NSCharacterSet.whitespaceCharacterSet];
      }
      if (date != nil) {
        changed[@"date"] = date;
      }
      if (completed != nil) {
        changed[@"completed"] = @(completed.boolValue);
      }
      updated = [changed copy];
      list[i] = updated;
      [self save];
      break;
    }
  }
  if (updated == nil) {
    reject(@"E_NOT_FOUND", [NSString stringWithFormat:@"No todo with id %@", todoId], nil);
  } else {
    resolve(updated);
  }
}

- (void)remove:(NSString *)todoId
       resolve:(RCTPromiseResolveBlock)resolve
        reject:(RCTPromiseRejectBlock)reject
{
  BOOL removed = NO;
  @synchronized(self) {
    NSMutableArray *list = [self load];
    NSIndexSet *matches = [list indexesOfObjectsPassingTest:^BOOL(
                                    NSDictionary *todo, NSUInteger idx, BOOL *stop) {
      return [todo[@"id"] isEqualToString:todoId];
    }];
    removed = matches.count > 0;
    if (removed) {
      [list removeObjectsAtIndexes:matches];
      [self save];
    }
  }
  resolve(@(removed));
}

- (void)clear:(RCTPromiseResolveBlock)resolve reject:(RCTPromiseRejectBlock)reject
{
  @synchronized(self) {
    [[self load] removeAllObjects];
    [self save];
  }
  resolve(nil);
}

#pragma mark - Sync methods (plain return value in the spec)

- (NSNumber *)count
{
  @synchronized(self) {
    return @([self load].count);
  }
}

- (NSDictionary *)getInfo
{
  return @{
    @"platform" : [NSString
        stringWithFormat:@"iOS %@ (Objective-C++)", UIDevice.currentDevice.systemVersion],
    @"storage" : [NSString stringWithFormat:@"NSUserDefaults \"%@\"", kSuiteName],
    @"key" : kTodosKey,
  };
}

#pragma mark - Storage

/// Reads the JSON from NSUserDefaults the first time; then uses memory.
- (NSMutableArray<NSDictionary *> *)load
{
  if (_todos != nil) {
    return _todos;
  }
  _todos = [NSMutableArray new];
  NSString *json = [_defaults stringForKey:kTodosKey];
  NSData *data = [json dataUsingEncoding:NSUTF8StringEncoding];
  if (data != nil) {
    NSArray *saved = [NSJSONSerialization JSONObjectWithData:data options:0 error:nil];
    if ([saved isKindOfClass:NSArray.class]) {
      [_todos addObjectsFromArray:saved];
    }
  }
  return _todos;
}

- (void)save
{
  NSData *data = [NSJSONSerialization dataWithJSONObject:[self load] options:0 error:nil];
  NSString *json = [[NSString alloc] initWithData:data encoding:NSUTF8StringEncoding];
  [_defaults setObject:json forKey:kTodosKey];
}

@end
