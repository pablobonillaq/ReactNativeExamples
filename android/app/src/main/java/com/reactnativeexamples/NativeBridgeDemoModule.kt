package com.reactnativeexamples

import android.os.Handler
import android.os.Looper
import com.facebook.react.bridge.Arguments
import com.facebook.react.bridge.Callback
import com.facebook.react.bridge.Promise
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.bridge.ReadableMap
import com.facebook.react.bridge.ReadableType
import com.facebook.react.bridge.WritableMap
import com.reactnativeexamples.specs.NativeBridgeDemoSpec

/**
 * Turbo Native Module for the "Bridging" screen. Each method shows one way
 * JS and Kotlin talk to each other. NativeBridgeDemoSpec is generated by
 * Codegen from specs/NativeBridgeDemo.ts.
 *
 * How spec types arrive here:
 *   string → String, number → Double, boolean → Boolean,
 *   object → ReadableMap (in) / WritableMap (out), Array → ReadableArray,
 *   Promise<T> → extra Promise parameter, function → Callback.
 */
class NativeBridgeDemoModule(reactContext: ReactApplicationContext) :
  NativeBridgeDemoSpec(reactContext) {

  override fun getName() = NAME

  // ---------------------------------------------------------------------
  // 1. Sync: runs on the JS thread, JS waits for the return value.
  // ---------------------------------------------------------------------

  override fun currentThread(): String = Thread.currentThread().name

  override fun add(a: Double, b: Double): Double = a + b

  // ---------------------------------------------------------------------
  // 2. Async: runs on a native background thread; resolves a Promise.
  // ---------------------------------------------------------------------

  override fun asyncThread(promise: Promise) {
    promise.resolve(Thread.currentThread().name)
  }

  override fun addAsync(a: Double, b: Double, promise: Promise) {
    promise.resolve(a + b)
  }

  // ---------------------------------------------------------------------
  // 3. Callback: a JS function native can call once.
  // ---------------------------------------------------------------------

  override fun withCallback(value: Double, callback: Callback) {
    callback.invoke("Kotlin got $value and sends back ${value * 2}")
  }

  // ---------------------------------------------------------------------
  // 4. Events: native decides when to send. Here, a timer on the main thread.
  // ---------------------------------------------------------------------

  private val mainHandler = Handler(Looper.getMainLooper())
  private var ticker: Runnable? = null
  private var tickCount = 0

  override fun startTicking(intervalMs: Double) {
    val interval = intervalMs.toLong().coerceAtLeast(100L)
    // All timer state is touched only on the main thread.
    mainHandler.post {
      stopTimer()
      tickCount = 0
      val runnable =
        object : Runnable {
          override fun run() {
            tickCount++
            // emitOnTick is generated from `readonly onTick: EventEmitter<…>`.
            emitOnTick(
              Arguments.createMap().apply {
                putInt("count", tickCount)
                putDouble("timestamp", System.currentTimeMillis().toDouble())
                putString("thread", Thread.currentThread().name)
              },
            )
            mainHandler.postDelayed(this, interval)
          }
        }
      ticker = runnable
      mainHandler.postDelayed(runnable, interval)
    }
  }

  override fun stopTicking() {
    mainHandler.post { stopTimer() }
  }

  private fun stopTimer() {
    ticker?.let { mainHandler.removeCallbacks(it) }
    ticker = null
  }

  /** Called when the JS runtime goes away (reload): stop sending events. */
  override fun invalidate() {
    mainHandler.post { stopTimer() }
    super.invalidate()
  }

  // ---------------------------------------------------------------------
  // 5. Type conversion: say what each JS value became in Kotlin.
  // ---------------------------------------------------------------------

  override fun echo(value: ReadableMap): WritableMap {
    val result = Arguments.createMap()
    val keys = value.keySetIterator()
    while (keys.hasNextKey()) {
      val key = keys.nextKey()
      val description =
        when (value.getType(key)) {
          ReadableType.Null -> "null"
          ReadableType.Boolean -> "Boolean ${value.getBoolean(key)}"
          // Every JS number arrives as a Double, even 42.
          ReadableType.Number -> "Double ${value.getDouble(key)}"
          ReadableType.String -> "String \"${value.getString(key)}\""
          ReadableType.Map -> "ReadableMap (${value.getMap(key)?.toHashMap()?.size ?: 0} keys)"
          ReadableType.Array -> "ReadableArray (${value.getArray(key)?.size() ?: 0} items)"
        }
      result.putString(key, description)
    }
    return result
  }

  // ---------------------------------------------------------------------
  // 6. Errors: reject with a code JS can read as error.code.
  // ---------------------------------------------------------------------

  override fun fail(code: String, message: String, promise: Promise) {
    promise.reject(code, message)
  }

  companion object {
    /** Must match TurboModuleRegistry.get('NativeBridgeDemo') in the spec. */
    const val NAME = "NativeBridgeDemo"
  }
}
